// Regenerates kit-templates.js (the deploy and kit scripts as importable strings) from the *.src.mjs / *.body.mjs files.
//   node tools/sailpoint-workbench/build-template.mjs
import fs from "node:fs";
const dir = new URL("./", import.meta.url);
const read = (f) => fs.readFileSync(new URL(f, dir), "utf8");
const common = read("kit-common.src.mjs");
const scripts = {
	DEPLOY_SCRIPT: read("deploy.src.mjs"),
	ENTITLEMENT_SCRIPT: "#!/usr/bin/env node\n" + common + "\n" + read("kit-entitlements.body.mjs"),
	CAMPAIGN_SCRIPT: "#!/usr/bin/env node\n" + common + "\n" + read("kit-campaigns.body.mjs"),
};
let out = "// GENERATED by build-template.mjs from deploy.src.mjs, kit-common.src.mjs and kit-*.body.mjs. Do not edit.\n";
for (const [k, v] of Object.entries(scripts)) out += `export const ${k} = ${JSON.stringify(v)};\n`;
fs.writeFileSync(new URL("kit-templates.js", dir), out);
// syntax check each generated script
fs.mkdirSync("/tmp/kitcheck", { recursive: true });
for (const [k, v] of Object.entries(scripts)) fs.writeFileSync(`/tmp/kitcheck/${k}.mjs`, v);
